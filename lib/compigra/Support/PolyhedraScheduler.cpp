bool compigra::isSinglePathStore(Value srcVal, affine::AffineStoreOp storeOp,
                                 std::queue<Operation *> &queOps) {
  auto storeVal = storeOp.getValueToStore();
  // check whether storeVal is only generated by srcVal
  if (storeVal == srcVal)
    return true;

  // if srcVal undergoes a series of arithmetic operations with constants,
  // return true
  auto getSingleUser = [&](Value val) {
    auto users = val.getUsers();
    if (users.empty())
      return (Operation *)nullptr;

    // Take the first user as reference
    Operation *firstUser = *users.begin();

    // Ensure all users are the same operation
    for (auto *u : users) {
      if (u != firstUser)
        return (Operation *)nullptr;
    }

    // Check the user has exactly one result
    if (firstUser->getNumResults() != 1)
      return (Operation *)nullptr;

    // Check whether all other operands are constants
    for (auto operand : firstUser->getOperands()) {
      if (operand != val) {
        if (!operand.getDefiningOp() ||
            !isa<arith::ConstantOp>(operand.getDefiningOp()))
          return (Operation *)nullptr;
      }
    }

    return firstUser;
  };

  Operation *singleUser = getSingleUser(srcVal);
  while (singleUser) {
    if (singleUser)
      queOps.push(singleUser);
    if (singleUser->getResult(0) == storeVal)
      return true;
    singleUser = getSingleUser(singleUser->getResult(0));
  }
  return false;
}

void compigra::getAllStatements(
    affine::AffineForOp outerFor,
    SmallVector<SmallVector<Operation *>> &statements) {
  outerFor.walk([&statements](mlir::Operation *op) {
    if (isa<affine::AffineLoadOp, affine::AffineStoreOp>(op)) {
      SmallVector<Operation *> opList;
      opList.push_back(op);
      // insert all arithmatic or constant operations after the load/store
      auto curOp = op->getNextNode();
      while (curOp) {
        // if curOp is a load/store or yield or loop, stop
        if (isa<affine::AffineLoadOp, affine::AffineStoreOp,
                affine::AffineYieldOp, affine::AffineForOp>(curOp)) {
          break;
        }
        opList.push_back(curOp);
        curOp = curOp->getNextNode();
      }

      statements.push_back(opList);
    }
  });
}

int getStatementLevel(AffineForOp rootFor, Operation *op) {
  auto forOp = dyn_cast<AffineForOp>(op->getParentOp());
  int level = 1;
  auto curBlock = forOp->getBlock();
  // Find all enclosing loops and their bounds
  while (curBlock && curBlock != rootFor->getBlock()) {
    level++;
    curBlock =
        curBlock->getParentOp() ? curBlock->getParentOp()->getBlock() : nullptr;
  }
  return level;
}

bool isProducer(Operation *producer, Operation *consumer) {
  for (Value result : producer->getResults()) {
    for (Value operand : consumer->getOperands()) {
      if (result == operand) {
        return true;
      }
    }
  }
  return false;
}

